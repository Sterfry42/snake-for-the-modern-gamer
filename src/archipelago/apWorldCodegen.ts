/**
 * AP World Code Generator
 *
 * The Python AP world's data tables (`apworld/snaked_revised_revamped/locations.py`
 * and `items.py`) are generated from the browser's Archipelago manifest so the
 * generator side can never drift from the client side.
 *
 * Workflow: change the manifest (or the game catalog it derives from), then run
 * `npm run build:apworld`, which regenerates these tables before packaging the
 * `.apworld` zip. `src/archipelago/__tests__/generateApWorld.test.ts` keeps the
 * committed tables in sync and fails the suite when they are not.
 */
import { ARTIFACT_DEFINITIONS } from '../artifacts/artifacts.js';
import { CARD_DEFINITIONS } from '../cards/cardGame.js';
import {
  AP_ACHIEVEMENT_GOAL_LOCATION,
  AP_ACHIEVEMENT_LOCATIONS,
  AP_ALL_ITEM_LIST,
  AP_PHASE_1_LOCATION_LIST,
  AP_PHASE_2_ARCHAEOLOGY_LOCATIONS,
  AP_PHASE_2_APPLE_LOCATIONS,
  AP_PHASE_2_APPLE_TYPES,
  AP_PHASE_2_ARTIFACT_LOCATIONS,
  AP_PHASE_2_BOSS_LOCATIONS,
  AP_PHASE_2_CARD_LOCATIONS,
  AP_PHASE_2_CARD_TABLE_LOCATIONS,
  AP_PHASE_2_CORE_ITEM_IDS,
  AP_PHASE_2_ITEM_LOCATIONS,
  AP_PHASE_2_LENGTH_LOCATIONS,
  AP_PHASE_2_QUEST_LOCATIONS,
  AP_PHASE_2_QUESTS,
  AP_PHASE_2_SCORE_LOCATIONS,
  type ArchipelagoItemDefinition,
  type ArchipelagoLocationDefinition,
} from './archipelagoCheckManifest.js';

export const AP_WORLD_GAME_NAME = 'Snaked. Revised. Revamped.';
export const AP_WORLD_LOCATION_BASE_ID = 912000000;
export const AP_WORLD_ITEM_BASE_ID = 913000000;

function pyString(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;
}

function pyDict(entries: Record<string, number>, indent = '    '): string {
  const lines = Object.entries(entries).map(
    ([key, value]) => `${indent}${pyString(key)}: ${value},`,
  );
  return `{\n${lines.join('\n')}\n}`;
}

function pyDictOfStrings(entries: Record<string, string>, indent = '    '): string {
  const lines = Object.entries(entries).map(
    ([key, value]) => `${indent}${pyString(key)}: ${pyString(value)},`,
  );
  return `{\n${lines.join('\n')}\n}`;
}

function pyTupleList(entries: ReadonlyArray<readonly [string, string]>, indent = '    '): string {
  const lines = entries.map(
    ([first, second]) => `${indent}(${pyString(first)}, ${pyString(second)}),`,
  );
  return `[\n${lines.join('\n')}\n]`;
}

function pyStringList(entries: readonly string[], indent = '    '): string {
  const lines = entries.map((entry) => `${indent}${pyString(entry)},`);
  return `[\n${lines.join('\n')}\n]`;
}

/** Every location in the Python catalog, in stable emission order. */
export function apWorldLocationCatalog(): ArchipelagoLocationDefinition[] {
  return [
    ...AP_PHASE_1_LOCATION_LIST,
    ...AP_PHASE_2_SCORE_LOCATIONS,
    ...AP_PHASE_2_LENGTH_LOCATIONS,
    ...AP_PHASE_2_APPLE_LOCATIONS,
    ...AP_PHASE_2_QUEST_LOCATIONS,
    ...AP_PHASE_2_ITEM_LOCATIONS,
    ...AP_PHASE_2_CARD_LOCATIONS,
    ...AP_PHASE_2_CARD_TABLE_LOCATIONS,
    ...AP_PHASE_2_ARTIFACT_LOCATIONS,
    ...AP_ACHIEVEMENT_LOCATIONS,
    AP_ACHIEVEMENT_GOAL_LOCATION,
    ...AP_PHASE_2_ARCHAEOLOGY_LOCATIONS,
    ...AP_PHASE_2_BOSS_LOCATIONS,
  ];
}

function assertUniqueKeys(catalog: readonly { key: string }[]): void {
  const seen = new Set<string>();
  for (const entry of catalog) {
    if (seen.has(entry.key)) {
      throw new Error(`Duplicate AP location key in generated catalog: ${entry.key}`);
    }
    seen.add(entry.key);
  }
}

export function generateLocationsPython(): string {
  const catalog = apWorldLocationCatalog();
  assertUniqueKeys(catalog);

  const locationTable = pyDict(
    Object.fromEntries(catalog.map((location) => [location.name, location.id])),
  );
  const keyToName = pyDictOfStrings(
    Object.fromEntries(catalog.map((location) => [location.key, location.name])),
  );
  const coreItemIds = pyStringList([...AP_PHASE_2_CORE_ITEM_IDS]);
  const cardDefinitions = pyTupleList(
    CARD_DEFINITIONS.map((card) => [card.id, card.name] as const),
  );
  const artifactDefinitions = pyTupleList(
    ARTIFACT_DEFINITIONS.map((artifact) => [artifact.id, artifact.name] as const),
  );
  const appleTypes = pyStringList([...AP_PHASE_2_APPLE_TYPES]);
  const quests = pyTupleList(AP_PHASE_2_QUESTS);
  const achievements = pyTupleList(
    AP_ACHIEVEMENT_LOCATIONS.map((location) => [location.key, location.name] as const),
  );

  return `"""Generated by src/archipelago/apWorldCodegen.ts from the browser Archipelago
manifest. Do not edit by hand; run \`npm run build:apworld\` to regenerate and
repackage the world. The test suite fails when this file is out of sync.
"""

from BaseClasses import Location


LOCATION_BASE_ID = ${AP_WORLD_LOCATION_BASE_ID}


CORE_ITEM_IDS = ${coreItemIds}

CARD_DEFINITIONS = ${cardDefinitions}

ARTIFACT_DEFINITIONS = ${artifactDefinitions}

APPLE_TYPES = ${appleTypes}

QUESTS = ${quests}

ACHIEVEMENT_LOCATIONS = ${achievements}

location_table = ${locationTable}

location_key_to_name = ${keyToName}

location_name_to_key = {name: key for key, name in location_key_to_name.items()}

location_groups = {
    "Score": {name for name in location_table if name.startswith("Reach Score")},
    "Length": {name for name in location_table if name.startswith("Reach Length")},
    "Apples": {name for name in location_table if name.startswith("Eat")},
    "Quests": {name for name in location_table if name.startswith("Complete")},
    "Items": {name for name in location_table if name.startswith("Find")},
    "Cards": {name for name in location_table if name.startswith("Collect")},
    "Card Tables": {name for name in location_table if name.startswith("Win at")},
    "Artifacts": {name for name in location_table if name.startswith("Recover")},
    "Bosses": {"Defeat Jason Statham"},
    "Achievements": {name for _, name in ACHIEVEMENT_LOCATIONS},
}


class SnakedLocation(Location):
    game = ${pyString(AP_WORLD_GAME_NAME)}
`;
}

function itemMetadataEntry(item: ArchipelagoItemDefinition): string {
  const parts: string[] = [`"kind": ${pyString(item.kind)}`];
  if (item.kind === 'score-bundle' || item.kind === 'length-bundle') {
    parts.push(`"amount": ${item.amount ?? 0}`);
  }
  if (item.itemId !== undefined) parts.push(`"item_id": ${pyString(item.itemId)}`);
  if (item.cardId !== undefined) parts.push(`"card_id": ${pyString(item.cardId)}`);
  if (item.artifactId !== undefined) parts.push(`"artifact_id": ${pyString(item.artifactId)}`);
  if (item.trapId !== undefined) parts.push(`"trap_id": ${pyString(item.trapId)}`);
  parts.push(`"classification": ${pyString(item.classification ?? 'useful')}`);
  return `{${parts.join(', ')}}`;
}

export function generateItemsPython(): string {
  const items = [...AP_ALL_ITEM_LIST];
  assertUniqueKeys(items);

  const itemTable = pyDict(Object.fromEntries(items.map((item) => [item.name, item.id])));
  const keyToName = pyDictOfStrings(Object.fromEntries(items.map((item) => [item.key, item.name])));
  const metadata = items
    .map((item) => `    ${pyString(item.name)}: ${itemMetadataEntry(item)},`)
    .join('\n');

  return `"""Generated by src/archipelago/apWorldCodegen.ts from the browser Archipelago
manifest. Do not edit by hand; run \`npm run build:apworld\` to regenerate and
repackage the world. The test suite fails when this file is out of sync.
"""

from BaseClasses import Item, ItemClassification


ITEM_BASE_ID = ${AP_WORLD_ITEM_BASE_ID}


item_table = ${itemTable}

item_key_to_name = ${keyToName}

item_metadata = {
${metadata}
}

item_groups = {
    "Score Bundles": {name for name, meta in item_metadata.items() if meta["kind"] == "score-bundle"},
    "Length Bundles": {name for name, meta in item_metadata.items() if meta["kind"] == "length-bundle"},
    "Cards": {name for name, meta in item_metadata.items() if meta["kind"] == "card"},
    "Artifacts": {name for name, meta in item_metadata.items() if meta["kind"] == "artifact"},
    "Traps": {name for name, meta in item_metadata.items() if meta["kind"] == "trap"},
}


class SnakedItem(Item):
    game = ${pyString(AP_WORLD_GAME_NAME)}


def get_item_classification(name: str) -> ItemClassification:
    classification = item_metadata[name].get("classification", "filler")
    if classification == "progression":
        return ItemClassification.progression
    if classification == "useful":
        return ItemClassification.useful
    if classification == "trap":
        return ItemClassification.trap
    return ItemClassification.filler
`;
}
